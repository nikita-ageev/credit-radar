def compare(regnums, dt, with_pnl=True, with_n=True, refresh=False):
    """Сравнение банков на одну дату. Возвращает {regnum: {метрики}}."""
    out = {}
    for rn in regnums:
        if rn is None:
            continue
        bal = f101(rn, dt, refresh)
        row = {"regnum": rn}
        row.update(retail_metrics(bal) or {})
        if with_pnl:
            row["pnl"] = pnl_metrics(rn, dt, bal, refresh)
        if with_n:
            n = f135(rn, dt, refresh)
            row["нормативы"] = (n or {}).get("нормативы")
        out[rn] = row
    return out


def history(regnum, months=12, upto=None):
    """Ряд помесячных метрик розницы: [{dt, розница_срочная, резерв…}, …] от старых к новым.
    Каждая форма 101 даёт остатки на начало и конец своего месяца, так что ряд из N форм
    покрывает N+1 отчётную дату; берём исходящие остатки — они и есть точки ряда."""
    d = _first_of_month(upto and date(*map(int, upto.split("-"))) or core.msk().date())
    out = []
    for _ in range(months):
        m = retail_metrics(f101(regnum, d.isoformat()))
        if m:
            out.append(m)
        d = _prev_month(d)
    return list(reversed(out))


def _fmt(v, mul, dec):
    if v is None:
        return "н/д"
    v = v * mul
    s = f"{v:,.{dec}f}".replace(",", " ").replace(".", ",")
    return s


def compare_table(cmp_result, names=None):
    """Markdown-таблица из результата compare()."""
    names = names or {}
    rns = list(cmp_result)
    head = ["Показатель"] + [names.get(r, str(r)) for r in rns]
    lines = ["| " + " | ".join(head) + " |",
             "|" + "|".join(["---"] * len(head)) + "|"]
    for key, label, mul, dec in FIELDS:
        lines.append("| " + " | ".join([label] +
                     [_fmt(cmp_result[r].get(key), mul, dec) for r in rns]) + " |")
    if any(cmp_result[r].get("pnl") for r in rns):
        for key, label, mul, dec in PNL_FIELDS:
            lines.append("| " + " | ".join([label] +
                         [_fmt((cmp_result[r].get("pnl") or {}).get(key), mul, dec)
                          for r in rns]) + " |")
    if any(cmp_result[r].get("нормативы") for r in rns):
        for n in ("Н1.0", "Н1.2", "Н1.1"):
            lines.append("| " + " | ".join([f"{n}, %"] +
                         [_fmt((cmp_result[r].get("нормативы") or {}).get(n), 1, 2)
                          for r in rns]) + " |")
    return "\n".join(lines)



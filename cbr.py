# ───────────────────────────── форма 101 ─────────────────────────────

_SECT = re.compile(r"^([АБВГ])\.\s")


def f101(regnum, dt, refresh=False):
    """Оборотная ведомость. Возвращает словарь или None, если на дату данных нет.

    {
      'form': 101, 'regnum':…, 'dt': '2026-08-01', 'unit': 'тыс. руб.',
      'title': …,
      'legend': {'45.2': [455, 457], …},            # расшифровка склеенных кодов со страницы
      'accounts': {                                  # плоский ключ 'раздел/сторона/счёт'
          'А/актив/45.2': {'счет': '45.2', 'раздел': 'А', 'сторона': 'актив',
                           'название': …,
                           'вх': 18_9…,             # входящий остаток, тыс. руб.
                           'исх': 19_4…,            # исходящий остаток, тыс. руб.
                           'дебет': None, 'кредит': None,   # в публичной версии не заполнены
                           'колонки': [ … 21 значение … ]},
          …
      }
    }
    """
    html, err = fetch(regnum, 101, dt, refresh)
    if not html:
        return None
    tbl = tables(html)
    if not tbl:
        return None
    rows = tbl[0]

    # Сноска внизу страницы: «— 45.2 — cумма балансовых счетов 455, 457».
    legend = {}
    for code, lst in re.findall(r"—\s*(\d\d\.\d)\s*—\s*c?умма\s+\w+\s+счетов</nobr>\s*([\d,\s]+)", html):
        legend[code] = [int(x) for x in re.findall(r"\d+", lst)]

    sect, side, acc = None, None, {}
    for r in rows:
        if len(r) == 1:                       # строка-заголовок раздела
            m = _SECT.match(r[0])
            if m:
                sect, side = m.group(1), None
            elif r[0] in ("Актив", "Пассив"):
                side = r[0].lower()
            continue
        if len(r) != 21:
            continue                          # шапка таблицы (4/2/6/20 ячеек) и нумерация колонок
        code = r[0].strip()
        if not re.fullmatch(r"\d{3,5}|\d\d\.\d", code):
            continue                          # строка «1 2 3 …» с номерами колонок
        cols = [num(x) for x in r]
        key = f"{sect}/{side}/{code}"
        acc[key] = {
            "счет": code, "раздел": sect, "сторона": side,
            "название": NAMES.get(code, ""),
            "вх": cols[5], "исх": cols[20],
            # обороты: колонки 7-11 (дебет) и 12-16 (кредит), итоги — 11 и 16.
            # В публичной версии формы они пустые, оставляем None явно.
            "дебет": cols[10], "кредит": cols[15],
            "колонки": cols,
        }
    if not acc:
        return None
    return {"form": 101, "regnum": regnum, "dt": dt, "unit": "тыс. руб.",
            "title": title(html), "legend": legend, "accounts": acc}


def _a(d, code, side="актив", sect="А"):
    """Остаток на конец периода по коду; 0, если счёта нет."""
    r = d["accounts"].get(f"{sect}/{side}/{code}")
    return (r or {}).get("исх") or 0


def _a_in(d, code, side="актив", sect="А"):
    r = d["accounts"].get(f"{sect}/{side}/{code}")
    return (r or {}).get("вх") or 0


def _sum(d, codes, side="актив", sect="А", field="исх"):
    return sum((d["accounts"].get(f"{sect}/{side}/{c}") or {}).get(field) or 0 for c in codes)



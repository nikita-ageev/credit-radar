#                       в т.ч. 40817 (физлица). Т.е. небольшая часть розницы (овердрафты
#                       по текущим счетам) сидит здесь, а не в 45.2. Разделить нельзя.
#   454             — кредиты индивидуальным предпринимателям. Формально это не физлица,
#                       но у ряда игроков ИП-кредиты продаются как розничный продукт.
#                       Считаем отдельной строкой, в розницу по умолчанию НЕ включаем.

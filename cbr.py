# ───────────────────────────── форма 102 (ОФР) ─────────────────────────────
#
# Публичная ф.102 даёт ТОЛЬКО итоги по разделам («Итого по разделу N») и итоговые
# символы 01000 / 03000 / 61101. Разбивки по символам (а значит — по типам заёмщиков)
# нет. Поэтому процентный доход по рознице отдельно НЕ считается; всё, что ниже, —
# показатели по банку целиком. Форма накопительная с начала года.
#
# Раздел ↔ смысл (Положение № 810-П, приложение к ф.0409102):
#   Часть 1 Раздел 1  — процентные доходы (кредиты + ценные бумаги + МБК)
#   Часть 1 Раздел 2  — комиссионные доходы, увеличивающие процентные (в составе ЭПС)
#   Часть 1 Раздел 5  — доходы от ВОССТАНОВЛЕНИЯ резервов на возможные потери
#   Часть 2 Раздел 7  — комиссионные и аналогичные доходы (основная комиссия)
#   Часть 3 Раздел 1  — процентные расходы (стоимость фондирования)
#   Часть 3 Раздел 7  — расходы по ФОРМИРОВАНИЮ резервов на возможные потери
#   Часть 4 Раздел 8  — операционные расходы (обеспечение деятельности) ≈ OPEX
# ⚠ Разделы 6 и 8 части 2 и разделы 6-7 части 4 показаны только суммой и содержат
#   ВАЛОВЫЕ обороты по переоценке валюты (у Сбера ~134 трлн за полугодие). Строки
#   «Всего доходов» / «Всего расходов» из-за этого экономического смысла не имеют —
#   в метриках НЕ используем, берём символ 01000 (прибыль до налога).

_F102_ROWS = {
    "проц_доходы":        ("Часть 1", "Раздел 1"),
    "комис_доходы_эпс":   ("Часть 1", "Раздел 2"),
    "восстановл_резервов":("Часть 1", "Раздел 5"),
    "комис_доходы":       ("Часть 2", "Раздел 7"),
    "проц_расходы":       ("Часть 3", "Раздел 1"),
    "создание_резервов":  ("Часть 3", "Раздел 7"),
    "опер_расходы":       ("Часть 4", "Раздел 8"),
}


def f102(regnum, dt, refresh=False):
    """ОФР. Итоги по разделам + прибыль. Накопительно с 01.01, тыс. руб."""
    html, err = fetch(regnum, 102, dt, refresh)
    if not html:
        return None
    tbl = tables(html)
    if not tbl or len(tbl[0]) < 10:
        return None
    part, res, sym = None, {}, {}
    for r in tbl[0]:
        if len(r) == 2 and r[1].startswith("Часть "):
            part = r[1].split(".")[0]
        elif len(r) == 6:
            name, symbol, val = r[1], r[2], num(r[5])
            if name.startswith("Итого по разделу"):
                res[(part, "Раздел " + name.split()[-1])] = val
            if symbol:
                sym[symbol] = val
    if not res:
        return None
    out = {"form": 102, "regnum": regnum, "dt": dt, "unit": "тыс. руб.",
           "title": title(html), "разделы": {f"{a} {b}": v for (a, b), v in res.items()},
           "символы": sym}
    for k, key in _F102_ROWS.items():
        out[k] = res.get(key)
    out["прибыль_до_налога"] = sym.get("01000")
    out["прибыль_после_налога"] = sym.get("61101")
    out["убыток_после_налога"] = sym.get("61102")
    out["чистое_доначисление_резервов"] = (
        (out["создание_резервов"] or 0) - (out["восстановл_резервов"] or 0))
    out["чистый_проц_доход"] = ((out["проц_доходы"] or 0) - (out["проц_расходы"] or 0))
    return out


def _months_ytd(dt):
    """Сколько месяцев накоплено в ф.102 на дату dt (dt = 1-е число)."""
    y, m, _ = (int(x) for x in dt.split("-"))
    return m - 1 if m > 1 else 12   # dt=2026-08-01 → отчёт за 01.01…31.07 → 7 месяцев


def pnl_metrics(regnum, dt, bal=None, refresh=False):
    """Производные P&L-метрики. Требуют ф.102 и (для знаменателей) ф.101 на ту же дату.

    Годовые ставки получаем приведением накопленного с начала года потока к году
    (× 12 / число месяцев). Знаменатель — средний за месяц остаток (вх+исх)/2 из ф.101.
    ⚠ Все показатели — ПО БАНКУ ЦЕЛИКОМ. Выделить розницу из ф.102 нельзя.
    """
    p = f102(regnum, dt, refresh)
    if not p:
        return None
    if bal is None:
        bal = f101(regnum, dt, refresh)
    k = 12.0 / _months_ytd(dt)
    out = {"regnum": regnum, "dt": dt, "мес_в_отчете": _months_ytd(dt),
           "проц_доходы_ytd": p["проц_доходы"], "проц_расходы_ytd": p["проц_расходы"],
           "комис_доходы_ytd": p["комис_доходы"],
           "чистое_доначисление_резервов_ytd": p["чистое_доначисление_резервов"],
           "прибыль_после_налога_ytd": p["прибыль_после_налога"]}
    if bal:
        loans_avg = (_sum(bal, LOAN_ACCS, field="вх") + _sum(bal, LOAN_ACCS, field="исх")) / 2
        fund_avg  = (_sum(bal, FUNDING_ACCS, "пассив", field="вх")
                     + _sum(bal, FUNDING_ACCS, "пассив", field="исх")) / 2
        # процентные активы = кредиты + вложения в ценные бумаги + размещённый межбанк:
        # именно они, а не один кредитный портфель, генерируют «Итого по разделу 1 части 1»
        earn = LOAN_ACCS + EARNING_EXTRA
        earn_avg = (_sum(bal, earn, field="вх") + _sum(bal, earn, field="исх")) / 2
        r = lambda a, b: round(100.0 * a * k / b, 2) if b else None
        # Защита от вырожденных знаменателей: у банков, где кредитования почти нет
        # (Яндекс Банк — портфель ~0 при 1 трлн клиентских остатков), деление
        # процентного дохода на кредитный портфель даёт бессмысленные тысячи процентов.
        # В таком случае честнее вернуть None, чем печатать мусор.
        thin = loans_avg < 0.05 * earn_avg
        rl = (lambda a, b: None) if thin else r
        out.update({
            "средний_кредитный_портфель": int(loans_avg),
            "средние_привлеченные_средства": int(fund_avg),
            # доходность: процентные доходы включают проценты по ценным бумагам и МБК,
            # поэтому это ВЕРХНЯЯ оценка доходности именно кредитного портфеля
            "доходность_кредитного_портфеля_pct": rl(p["проц_доходы"] or 0, loans_avg),
            "доходность_проц_активов_pct": r(p["проц_доходы"] or 0, earn_avg),
            "средние_процентные_активы": int(earn_avg),
            "стоимость_фондирования_pct": r(p["проц_расходы"] or 0, fund_avg),
            "cor_стоимость_риска_pct": rl(p["чистое_доначисление_резервов"], loans_avg),
            "_кредитование_несущественно": thin,
        })
        # NIM = чистый процентный доход / средние процентные активы. Это корректная
        # маржа. «Спред» (разница двух ставок) считается по разным базам — доходность
        # к активам, стоимость к пассивам — и потому систематически ниже NIM; держим
        # его как справочный, ориентироваться надо на NIM.
        out["чистая_процентная_маржа_pct"] = r(p["чистый_проц_доход"], earn_avg)
        if out.get("доходность_проц_активов_pct") and out.get("стоимость_фондирования_pct"):
            out["процентный_спред_пп"] = round(
                out["доходность_проц_активов_pct"] - out["стоимость_фондирования_pct"], 2)
    return out


# ───────────────────────────── форма 135 (нормативы) ─────────────────────────────

def f135(regnum, dt, refresh=False):
    """Обязательные нормативы: {'Н1.0': 14.633, 'Н1.1': …}. Значения в процентах."""
    html, err = fetch(regnum, 135, dt, refresh)
    if not html:
        return None
    tbl = tables(html)
    if not tbl or len(tbl[0]) < 3:
        return None
    vals, limits = {}, {}
    for r in tbl[0][1:]:
        if len(r) >= 3 and r[0].startswith("Н"):
            v = num(r[1])
            if v is not None:
                vals[r[0]] = v
                if num(r[2]) is not None:
                    limits[r[0]] = num(r[2])
    if not vals:
        return None
    return {"form": 135, "regnum": regnum, "dt": dt, "title": title(html),
            "нормативы": vals, "контрольные_значения": limits}


# ───────────────────────────── форма 123 (капитал) ─────────────────────────────

def f123(regnum, dt, refresh=False):
    """Расчёт капитала «Базель III». Возвращает {номер строки: (название, значение)}
    плюс ярлыки для трёх ключевых строк: базовый / основной / собственные средства."""
    html, err = fetch(regnum, 123, dt, refresh)
    if not html:
        return None
    tbl = tables(html)
    if not tbl or len(tbl[0]) < 10:
        return None
    rows, lines = {}, tbl[0]
    for r in lines:
        if len(r) >= 3 and re.fullmatch(r"\d+(\.\d+)*", r[0].strip()):
            rows[r[0].strip()] = (r[1], num(r[-1]))
    if not rows:
        return None
    # В публичной версии ф.123 заполнены только итоговые строки:
    #   000 — собственные средства (капитал) всего
    #   102 — базовый капитал   105 — добавочный капитал   203 — дополнительный капитал
    # Расшифровка источников и вычетов (строки 100.x, 104.x, 201.x) публикуется пустой.
    pick = lambda n: rows.get(n, (None, None))[1]
    base, add1, add2 = pick("102"), pick("105"), pick("203")
    return {"form": 123, "regnum": regnum, "dt": dt, "title": title(html),
            "строки": rows,
            "базовый_капитал": base,
            "добавочный_капитал": add1,
            "основной_капитал": (base + add1) if (base is not None and add1 is not None) else base,
            "дополнительный_капитал": add2,
            "собственные_средства": pick("000")}



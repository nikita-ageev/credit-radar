# ───────────────────────────── загрузка и кэш ─────────────────────────────

def _cache_path(regnum, form, dt):
    d = os.path.join(CACHE, f"f{form}")
    os.makedirs(d, exist_ok=True)
    return os.path.join(d, f"{regnum}_{dt}.html.gz")


def fetch(regnum, form, dt, refresh=False):
    """Сырой HTML формы. Кладём в state/cbr/f{форма}/{regnum}_{дата}.html.gz и
    повторно не тянем. Возвращает (html, ошибка).

    ВАЖНО: страница «нет данных» отдаётся с кодом 200 и пустой таблицей, а не 404.
    Поэтому кэшируем всё, что пришло, а «есть ли данные» решает уже парсер."""
    p = _cache_path(regnum, form, dt)
    if os.path.exists(p) and not refresh:
        try:
            with gzip.open(p, "rt", encoding="utf-8") as f:
                return f.read(), None
        except Exception:
            pass
    html, err = core.get(URL.format(form=form, regnum=regnum, dt=dt))
    if html is None:
        return None, err
    with gzip.open(p, "wt", encoding="utf-8") as f:
        f.write(html)
    return html, None


# ───────────────────────────── разбор HTML-таблиц ─────────────────────────────

_TAG   = re.compile(r"<[^>]+>")
_TABLE = re.compile(r"<table[^>]*>(.*?)</table>", re.S)
_TR    = re.compile(r"<tr[^>]*>(.*?)</tr>", re.S)
_TD    = re.compile(r"<t[dh][^>]*>(.*?)</t[dh]>", re.S)


def _cell(raw):
    t = _TAG.sub("", raw)
    for a, b in (("&nbsp;", " "), ("&amp;", "&"), ("&lt;", "<"), ("&gt;", ">"), ("\xa0", " ")):
        t = t.replace(a, b)
    return " ".join(t.split())


def tables(html):
    """Все таблицы страницы как список списков строк (строка = список ячеек-строк).
    Разметка ЦБ ровная: <table class="data spaced"> без вложенных таблиц."""
    return [[[_cell(c) for c in _TD.findall(tr)] for tr in _TR.findall(t)]
            for t in _TABLE.findall(html)]


def num(s):
    """'1 234 567' → 1234567; '11,961' → 11.961; пусто/прочерк → None."""
    if s is None:
        return None
    s = s.replace(" ", "").replace("\xa0", "").strip()
    if not s or s in {"-", "—", "х", "x", "X"}:
        return None
    s = s.replace(",", ".")
    if not re.fullmatch(r"[-+]?\d+(\.\d+)?", s):
        return None
    v = float(s)
    return int(v) if v.is_integer() and "." not in s else v


def title(html):
    m = re.search(r"<h1[^>]*>(.*?)</h1>", html, re.S)
    return _cell(m.group(1)) if m else ""



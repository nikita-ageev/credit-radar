PARSERS = {101: f101, 102: f102, 123: f123, 135: f135}


def _first_of_month(d):
    return date(d.year, d.month, 1)


def _prev_month(d):
    return _first_of_month(_first_of_month(d) - timedelta(days=1))


def latest_available(regnum=1481, form=101, back=8, today=None):
    """Последняя дата, на которую ЦБ РЕАЛЬНО опубликовал форму (не гадаем по календарю).

    Идём от 1-го числа текущего месяца назад и проверяем, что парсер вернул данные.
    Страница «нет данных» приходит с кодом 200 и пустой таблицей — поэтому проверяем
    именно результат разбора, а не HTTP-статус."""
    parse = PARSERS.get(form)
    if parse is None:
        return None
    d = _first_of_month(today or core.msk().date())
    for _ in range(back):
        dt = d.isoformat()
        if parse(regnum, dt) is not None:
            return dt
        d = _prev_month(d)
    return None


def _quarter_ends(today=None, n=5):
    """Последние n «первых чисел квартала» — публикуемые формы 805-814 квартальные."""
    d = _first_of_month(today or core.msk().date())
    while d.month not in (1, 4, 7, 10):
        d = _prev_month(d)
    out = []
    for _ in range(n):
        out.append(d.isoformat())
        d = _prev_month(_prev_month(_prev_month(d)))
    return out


def forms_available(regnum, forms=KNOWN_FORMS):
    """Какие формы и на какие даты реально опубликованы по конкретному банку.

    Для форм с парсером (101/102/123/135) — «есть ли разобранные данные» и на какую
    последнюю дату (перебор месяцев назад). Для квартальных форм 805-814 парсера нет:
    перебираем последние кварталы и отдаём сырой признак — сколько таблиц и строк
    на странице. Пустая страница (200 OK, таблица без строк) = данных нет."""
    out = {}
    for f in forms:
        if f in PARSERS:
            last = latest_available(regnum, f)
            out[f] = {"парсер": True, "последняя_дата": last, "данные": last is not None}
            continue
        rec = {"парсер": False, "данные": False, "последняя_дата": None}
        for d in _quarter_ends():
            html, err = fetch(regnum, f, d)
            if not html:
                rec["http"] = err
                continue
            t = tables(html)
            rows = sum(len(x) for x in t)
            # ⚠ Формы 805-814 у большинства банков отдаются ПУСТЫМ ШАБЛОНОМ: строки
            # с наименованиями есть, чисел нет. Поэтому признак «данные» — наличие
            # хотя бы одной числовой ячейки, а не количество строк.
            filled = sum(1 for tb in t for r in tb if any(num(c) is not None for c in r[2:]))
            rec.update({"таблиц": len(t), "строк": rows, "строк_с_числами": filled,
                        "дата": d, "заголовок": title(html)})
            if filled:
                rec.update({"данные": True, "последняя_дата": d})
                break
        out[f] = rec
    return out



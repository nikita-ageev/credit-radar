#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Регрессия блока «Итоги недели» (1.1.0, 21.09.2026): собирается из снимков дней без модели, ценовые изменения вперёд,
тихая неделя — одна строка, пропуски дней не ломают. Запуск: python3 evals/week_test.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import digest

C = lambda bank, prod, param, old, new, url="https://x/": {"bank": bank, "product": prod, "param": param, "old": old, "new": new, "url": url}
days = [
    {"date": "2026-09-15", "chs": [], "news": [{"title": "а"}, {"title": "б", "repeat": True}]},
    {"date": "2026-09-16", "chs": [C("МТС-Банк", "кредит наличными", "лимит", "получите до 15 млн ₽", ""),
                                   C("Альфа-Банк", "кредитная карта", "льготный период", "БП 60 дней", "БП 60 дней")], "news": []},
    {"date": "2026-09-17", "chs": [C("МТС-Банк", "кредитная карта", "ставка", "Ставка до 19,9%", "Ставка до 20,0%"),
                                   C("МТС-Банк", "кредит наличными", "ставка", "Ставка до 19,9%", "Ставка до 20,0%")], "news": [{"title": "в"}]},
    {"date": "2026-09-19", "chs": [C("ВТБ", "кредитная карта", "скидка/акция", "", "Акция 1 000 000 ₽")], "news": [{"title": "г"}]},
    {"date": "2026-09-20", "chs": [], "news": []},
]
t = digest.week_block(days, "15.09–21.09")
checks = [
    ("заголовок с датами", t.startswith("<b>Итоги недели</b> · 15.09–21.09")),
    ("счёт изменений и банков", "Изменений условий: 5 у 3 банков" in t),
    ("тихие дни и новости без повторов", "тихих дней: 2 из 5" in t and "новостей: 3" in t),
    ("МТС первым: ценовое изменение фрагментом «было/стало»", t.index("МТС-Банк") < t.index("Альфа-Банк") and "ставка было «Ставка до 19,9%», стало «Ставка до 20,0%»" in t),
    ("ещё одно ценовое у МТС посчитано", "и ещё 1 ценовое" in t),
    ("ссылка на банк", '<a href="https://x/">МТС-Банк</a>' in t),
    ("продукты перечислены", "(кредит наличными, кредитная карта)" in t),
    ("одинаковый текст у Альфы — не ценовое, без «было/стало»", "было" not in t.split("Альфа-Банк")[1].split("\n")[0]),
    ("длинные строки: только изменённый фрагмент", "было «…ставка до 19,9% годовых при», стало «…ставка до 20,0% годовых при»" in digest.week_block([{"date": "d", "chs": [C("Б", "п", "ставка", "Очень длинное описание условий по продукту, ставка до 19,9% годовых при выполнении условий", "Очень длинное описание условий по продукту, ставка до 20,0% годовых при выполнении условий")], "news": []}])),
    ("тихая неделя — одна строка", "значимых изменений условий у банков не найдено" in digest.week_block([{"date": "d", "chs": [], "news": [{"title": "x"}]}])),
    ("нет снимков — пусто", digest.week_block([]) == ""),
    ("мусор в снимках не ломает", "Итоги недели" in digest.week_block([{"date": "d", "chs": [None, {"x": 1}], "news": None}])),
]
fails = [n for n, ok in checks if not ok]
for n, ok in checks: print(("PASS " if ok else "FAIL ") + n)
if fails: print(t)
print("\nИТОГ:", "OK" if not fails else f"{len(fails)} FAIL")
sys.exit(1 if fails else 0)

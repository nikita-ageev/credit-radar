# ---------- клиент Anthropic ----------
def _post(payload, timeout=90, tries=3, hedge=8.0):
    """Хеджированный запрос: при зависшем соединении пускаем дубль, берём первый ответ."""
    body = json.dumps(payload).encode()
    req = urllib.request.Request("https://api.anthropic.com/v1/messages", data=body, headers={
        "x-api-key": KEY, "anthropic-version": "2023-06-01", "content-type": "application/json"})
    done = queue.Queue(); stop = threading.Event()
    def attempt():
        try:
            with urllib.request.urlopen(req, timeout=timeout) as r:
                d = json.load(r)
            if not stop.is_set(): done.put(("ok", d))
        except urllib.error.HTTPError as e:
            done.put(("fatal" if e.code in (400, 401, 403) else "err",
                      RuntimeError(f"HTTP {e.code}: {e.read()[:200].decode('utf-8','replace')}")))
        except Exception as e:
            done.put(("err", e))
    started = 0; last = None; deadline = time.time() + timeout + 5
    while time.time() < deadline:
        if started < tries:
            started += 1; threading.Thread(target=attempt, daemon=True).start()
        try:
            kind, val = done.get(timeout=hedge if started < tries else 10)
        except queue.Empty:
            continue
        if kind == "ok":
            stop.set(); return val
        last = val
        if kind == "fatal":
            stop.set(); raise last
    raise last or TimeoutError("Anthropic не ответил")


# Цены Anthropic, $ за миллион токенов: вход, выход, запись в кэш, чтение из кэша.
PRICES = {"claude-opus-5": (5, 25, 6.25, 0.5), "claude-sonnet-5": (2, 10, 2.5, 0.2),
          "claude-fable-5": (10, 50, 12.5, 1.0), "claude-fable-5-1": (10, 50, 12.5, 1.0), "claude-haiku-4-5": (1, 5, 1.25, 0.1)}
COSTS = os.path.join(HERE, "state", "costs.jsonl")

def _account(model, usage, what=""):
    p = PRICES.get(model, (5, 25, 6.25, 0.5))
    i, o = usage.get("input_tokens", 0), usage.get("output_tokens", 0)
    cw, cr = usage.get("cache_creation_input_tokens", 0), usage.get("cache_read_input_tokens", 0)
    usd = (i * p[0] + o * p[1] + cw * p[2] + cr * p[3]) / 1e6
    try:
        os.makedirs(os.path.dirname(COSTS), exist_ok=True)
        with open(COSTS, "a", encoding="utf-8") as f:
            f.write(json.dumps({"ts": time.strftime("%Y-%m-%dT%H:%M:%S"), "model": model, "what": what,
                                "in": i, "out": o, "cw": cw, "cr": cr, "usd": round(usd, 5)}, ensure_ascii=False) + "\n")
    except Exception:
        pass
    return usd

def spent(since=None, days=None):
    """Сумма расходов, $: с даты since (YYYY-MM-DD) или за последние days дней."""
    cutoff = since or (time.strftime("%Y-%m-%d", time.localtime(time.time() - 86400 * days)) if days else "0000")
    total = 0.0
    try:
        for line in open(COSTS, encoding="utf-8"):
            try:
                r = json.loads(line)
                if r["ts"][:10] >= cutoff: total += r["usd"]
            except Exception:
                continue
    except Exception:
        pass
    return total

def ctx_block(context):
    """Единый блок данных дня — БАЙТ В БАЙТ одинаковый во всех вызовах, чтобы кэш промптов
    срабатывал у генерации, ревизии и проверок (кэш общий внутри одной модели)."""
    return "ДАННЫЕ ДНЯ (всё, что есть; ничего сверх этого не существует):\n" + context

def ask(user_text, system=ANALYST, max_tokens=12000, timeout=90, cached_prefix=None, what=""):
    """cached_prefix — большой общий текст (контекст дня), идёт первым блоком с cache_control:
    повторные вызовы с тем же префиксом платят за него 10% цены."""
    if cached_prefix:
        content = [{"type": "text", "text": cached_prefix, "cache_control": {"type": "ephemeral"}},
                   {"type": "text", "text": user_text}]
    else:
        content = user_text
    d = _post({"model": MODEL, "max_tokens": max_tokens,
               "system": [{"type": "text", "text": system,
                           "cache_control": {"type": "ephemeral"}}],
               "messages": [{"role": "user", "content": content}]}, timeout=timeout)
    _account(MODEL, d.get("usage") or {}, what)
    return "".join(b.get("text", "") for b in d.get("content", []) if b.get("type") == "text")

def _json_out(raw):
    """JSON из ответа модели. Если ответ обрезан потолком токенов, пробуем спасти
    текст поста — лучше опубликовать разбор без графика, чем потерять всё."""
    s = raw.strip()
    i, j = s.find("{"), s.rfind("}")
    if i >= 0 and j > i:
        try:
            return json.loads(s[i:j + 1])
        except Exception:
            pass
    m = re.search(r'"title"\s*:\s*"((?:[^"\\]|\\.)*)"', s)
    b = re.search(r'"post"\s*:\s*"((?:[^"\\]|\\.)*)', s)
    if m and b:
        # Распаковку escape-последовательностей делаем ЧЕРЕЗ JSON, а не через
        # unicode_escape: тот работает поверх latin-1 и превращает кириллицу
        # в моджибейк вида "ÐÐ¢Ð". Ровно на этом сгорел один опубликованный пост.
        def unq(x):
            try:
                return json.loads('"' + x + '"')
            except Exception:
                return json.loads('"' + x.rstrip("\\") + '"')
        try:
            return {"importance": 3, "title": unq(m.group(1)),
                    "post": unq(b.group(1)).rstrip(), "facts": [], "chart": None,
                    "_truncated": True}
        except Exception:
            return None
    return None


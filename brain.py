def digest(items, extra=""):
    """items — [{bank, product, url, changes}]; extra — блок ЦБ/отзывов, если есть."""
    lines = ["СВОДКА ИЗМЕНЕНИЙ ЗА СУТКИ. Собери из них ОДИН пост.",
             "Правило отбора: в пост идёт только то, что меняет картину рынка. Мелочь — одной строкой "
             "в конце или вообще выброси. Начни с самого важного, а не по алфавиту.", ""]
    for it in items:
        lines += [f"— {it['bank']} / {it['product']} ({it['url']})",
                  "\n".join(it["changes"][:25]), ""]

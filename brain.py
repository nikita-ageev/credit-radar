def review_one(role_prompt, model, post_text, evidence=""):
    body = ["ТЕКСТ ПОСТА:", post_text, "",
            "Исходные данные, на которых он построен, — в блоке «ДАННЫЕ ДНЯ» выше.", REVIEW_SCHEMA]
    global MODEL
    saved = MODEL
    try:
        MODEL = model
        raw = ask("\n".join(body), system=role_prompt, max_tokens=6000, timeout=240,
                  cached_prefix=ctx_block(evidence[:40000]) if evidence else None, what="review:" + role_prompt[:12])
        d = _json_out(raw)
        if not d:
            # Важно отличать «проверяющий запретил» от «проверяющий не смог ответить»:
            # раньше нераспарсенный (обрезанный) ответ молча превращался в запрет,
            # и выглядело это как замечание без единого замечания.
            return {"verdict": "сбой", "issues": [], "summary":
                    f"ответ проверяющего не разобран ({len(raw)} знаков) — вероятно обрезан"}
        return d
    finally:
        MODEL = saved

def review(post_text, evidence=""):
    """Возвращает [(роль, модель, результат)] по всем проверяющим."""
    out = []
    for role, prompt, model in REVIEWERS:
        try:
            r = review_one(prompt, model, post_text, evidence)
            if isinstance(r, list):                        # модель вернула массив замечаний без обёртки (13.09.2026)
                r = {"verdict": "правки", "issues": [i for i in r if isinstance(i, dict)], "summary": "список замечаний"}
            if not isinstance(r, dict):
                raise TypeError(f"ответ проверяющего: {type(r).__name__}")
            if not isinstance(r.get("issues"), list):
                r["issues"] = []
            r["issues"] = [i for i in r["issues"] if isinstance(i, dict)]
        except Exception as e:
            r = {"verdict": "нельзя", "issues": [{"severity": "критично",
                 "what": f"проверка не отработала: {type(e).__name__}: {str(e)[:80]}",
                 "fix": "повторить проверку"}], "summary": "сбой проверки"}
        out.append((role, model, r))
    return out



def analyze_change(bank, product, url, changes, context=""):
    """changes — список строк диффа (+ добавлено / - убрано)."""
    body = [f"КОНКУРЕНТ: {bank}", f"ПРОДУКТ: {product}", f"ИСТОЧНИК: {url}", "",
            "ЧТО ИЗМЕНИЛОСЬ НА СТРАНИЦЕ (+ появилось, − исчезло):",
            "\n".join(changes[:60])]
    if context:
        body += ["", "ДОПОЛНИТЕЛЬНЫЙ КОНТЕКСТ (проверенные данные, можно использовать в расчётах):", context]
    body += ["", "Разбери это изменение по своим правилам.", SCHEMA]
    return _json_out(ask("\n".join(body), max_tokens=12000)) or {}


# -*- coding: utf-8 -*-
"""Стиль текста для канала: проверка на «ИИ-штампы», сложные фразы и жаргон.

Зачем отдельный модуль: модель пишет гладко, но узнаваемо — «ограничения честно»,
«конструкция», «трактовка», «витрины». Владелец канала это ловит с первого взгляда.
Линтер находит такие места до публикации; правка делается моделью по списку замечаний,
а простые замены — здесь, детерминированно.
"""
import re

# (регулярка, что не так / чем заменить)
BANNED = [
    (r"ограничени[яе] честно", "заголовок-штамп; напиши обычным предложением: «Выборка маленькая: …»"),
    (r"\bвитрин\w*", "жаргон; пиши «страница условий», «лендинг», «сайт банка»"),
    (r"действующих держател\w*", "канцелярит; «текущие клиенты» или «те, у кого карта уже есть»"),
    (r"\bконструкци\w*", "абстракция; скажи, что именно устроено и как"),
    (r"\bтрактовк\w*", "абстракция; «объяснение», «версия»"),
    (r"временн[оó]й структур\w*", "сложно; «когда банк начинает зарабатывать проценты»"),
    (r"экономически\b", "лишнее слово-связка"),
    (r"что опровергло бы", "формула из методички; если проверка нереалистична — убери совсем"),
    (r"стоит отметить|важно понимать|в условиях\b|следует подчеркнуть|нельзя не", "штамп"),
    (r"\bальфа к индексу|альфа за (день|неделю|месяц)", "жаргон; напиши буквально: с A до B ₽ (−N%), индекс за то же время …"),
    (r"\bп\.п\.", "проценты пунктов не пишем; буквально, в процентах и рублях"),
    (r"честно говоря|если честно|по сути\b|в целом\b", "слова-паразиты"),
    (r"механик[аи]\b", "жаргон; «правило», «как это работает»"),
    (r"вводн(ая|ой) механик", "штамп"),
]

TERMS = {  # безопасные автозамены (целые слова)
    r"\bу конкурентов\b": "у банков",
    r"\bконкурентов\b": "других банков",
    r"\bконкуренты\b": "другие банки",
    r"\bконкурентам\b": "другим банкам",
    r"\bконкурента\b": "другого банка",
    r"\bконкурент\b": "другой банк",
    r"\bконкурентн\w+\b": "рыночной",
    r"\bвитрине\b": "странице условий",
    r"\bвитрины\b": "страницы условий",
    r"\bвитрин\b": "страниц условий",
    r"\bвитрину\b": "страницу условий",
    r"\bвитрина\b": "страница условий",
    r"\bвитринах\b": "страницах условий",
    r"\bвитринными\b": "заявленными на сайте",
    r"\bвитринных\b": "заявленных на сайте",
}

MAX_SENT_WORDS = 30
AVG_SENT_WORDS = 20


def _plain(text):
    return re.sub(r"<[^>]+>", "", text or "")


def sentences(text):
    t = _plain(text)
    parts = re.split(r"(?<=[.!?…])\s+", t)
    return [p.strip() for p in parts if len(p.split()) >= 3]


def check(text):
    """Список замечаний {'what','where','fix'}; пусто — текст чистый."""
    issues = []
    plain = _plain(text)
    for rx, hint in BANNED:
        for m in re.finditer(rx, plain, re.I):
            s = plain[max(0, m.start() - 40): m.end() + 40].replace("\n", " ")
            issues.append({"what": f"«{m.group(0)}»", "where": s, "fix": hint})
    sents = sentences(plain)
    if sents:
        lens = [len(s.split()) for s in sents]
        avg = sum(lens) / len(lens)
        if avg > AVG_SENT_WORDS:
            issues.append({"what": f"средняя длина предложения {avg:.0f} слов",
                           "where": "", "fix": f"разбей длинные фразы; норма ≤ {AVG_SENT_WORDS}"})
        for s, n in zip(sents, lens):
            if n > MAX_SENT_WORDS:
                issues.append({"what": f"предложение из {n} слов", "where": s[:120] + "…",
                               "fix": "разбей на два-три"})
    return issues


def autofix(text):
    """Только безопасные замены терминов. Смысл не трогаем."""
    for rx, rep in TERMS.items():
        text = re.sub(rx, rep, text, flags=re.I)
    return text


def issues_for_model(issues, limit=12):
    """Замечания в виде списка для правки моделью."""
    return [{"severity": "важно", "what": f"Стиль: {i['what']}" + (f" — «{i['where']}»" if i.get("where") else ""),
             "fix": i["fix"]} for i in issues[:limit]]
